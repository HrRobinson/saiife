//! Writes `$OUT_DIR/builtin_packs.rs`: every shipped pack (`packs/*.toml`,
//! sorted by file name) parsed into `static` Rust data of the types in
//! `src/pack_raw.rs`, so no hook call parses the built-in TOML. The rules are
//! checked and compiled at run time as before (`pack::load_shipped`).
//!
//! The test `builtin_data_is_the_toml` (src/builtins.rs) parses the files
//! again and compares, so the data cannot drift from the TOML.

#[path = "src/pack_raw.rs"]
#[allow(dead_code)]
mod pack_raw;

use pack_raw::{
    OperandSyntax, RawMeta, RawPackFile, RawPathRule, RawRule, RuleAccess, RulePlatform, Str,
};
use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = root.join("packs");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed=src/pack_raw.rs");
    let mut names: Vec<String> = std::fs::read_dir(&dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| {
            e.expect("packs entry")
                .file_name()
                .into_string()
                .expect("pack file names are UTF-8")
        })
        .filter(|n| n.ends_with(".toml"))
        .collect();
    names.sort();
    let mut out = String::from(
        "// Generated by crates/guard/build.rs from packs/*.toml. Do not edit.\n\
         pub(crate) static BUILTIN_DATA: &[(&str, RawPackFile)] = &[\n",
    );
    for n in &names {
        let path = dir.join(n);
        println!("cargo:rerun-if-changed={}", path.display());
        let text =
            std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        // A pack that does not parse fails the build: a shipped pack is never
        // left out at run time for a typo.
        let raw: RawPackFile =
            toml::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        writeln!(out, "    ({n:?}, {}),", pack(&raw)).unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("builtin_packs.rs");
    std::fs::write(&dest, out).unwrap_or_else(|e| panic!("{}: {e}", dest.display()));
}

// Each writer destructures its type in full, so a new field fails this build
// until it is written out.

fn pack(p: &RawPackFile) -> String {
    let RawPackFile {
        pack,
        allow,
        deny,
        allow_path,
        deny_path,
    } = p;
    format!(
        "RawPackFile {{ pack: {}, allow: {}, deny: {}, allow_path: {}, deny_path: {} }}",
        meta(pack),
        list(allow, rule),
        list(deny, rule),
        list(allow_path, path_rule),
        list(deny_path, path_rule),
    )
}

fn meta(m: &RawMeta) -> String {
    let RawMeta {
        id,
        name,
        description,
        default_on,
        version,
        triggers,
        windows_triggers,
        substitution_failsafe,
        lazy,
    } = m;
    format!(
        "RawMeta {{ id: {}, name: {}, description: {}, default_on: {default_on}, \
         version: {version}, triggers: {}, windows_triggers: {}, \
         substitution_failsafe: {substitution_failsafe}, lazy: {lazy} }}",
        s(id),
        s(name),
        s(description),
        list(triggers, s),
        list(windows_triggers, s),
    )
}

fn rule(r: &RawRule) -> String {
    let RawRule {
        id,
        platform: plat,
        pattern,
        reason,
        whole_segment,
        after_env_change,
        peeled_wrappers,
        operand_match,
        operand_targets,
        when_option,
        command_options,
        command_long_options,
        command_signal_word,
        command_long_only,
        when_no_operand,
        target_options,
        operand_match_share,
        operand_min_len,
        operand_substitution,
        no_redirections,
    } = r;
    let share = match operand_match_share {
        Some(x) if x.is_finite() => format!("Some({x:?})"),
        Some(x) => panic!("rule {pattern:?}: operand_match_share {x} is not a number"),
        None => "None".to_string(),
    };
    let syntax = match operand_match {
        Some(OperandSyntax::Regex) => "Some(OperandSyntax::Regex)",
        Some(OperandSyntax::Glob) => "Some(OperandSyntax::Glob)",
        None => "None",
    };
    format!(
        "RawRule {{ id: {}, platform: {}, pattern: {}, reason: {}, \
         whole_segment: {whole_segment}, after_env_change: {after_env_change}, \
         peeled_wrappers: {peeled_wrappers}, operand_match: {syntax}, \
         operand_targets: {}, when_option: {}, command_options: {}, \
         command_long_options: {}, command_signal_word: {command_signal_word}, \
         command_long_only: {command_long_only}, when_no_operand: {when_no_operand}, \
         target_options: {}, operand_match_share: {share}, \
         operand_min_len: {operand_min_len}, operand_substitution: {operand_substitution}, \
         no_redirections: {no_redirections} }}",
        opt(id),
        platform(plat),
        s(pattern),
        opt(reason),
        list(operand_targets, s),
        list(when_option, s),
        opt(command_options),
        list(command_long_options, s),
        list(target_options, s),
    )
}

fn path_rule(r: &RawPathRule) -> String {
    let RawPathRule {
        platform: plat,
        glob,
        access,
        reason,
        ancestors,
    } = r;
    let access = match access {
        RuleAccess::Read => "RuleAccess::Read",
        RuleAccess::Write => "RuleAccess::Write",
        RuleAccess::Any => "RuleAccess::Any",
    };
    format!(
        "RawPathRule {{ platform: {}, glob: {}, access: {access}, reason: {}, \
         ancestors: {ancestors} }}",
        platform(plat),
        s(glob),
        opt(reason),
    )
}

fn platform(p: &Option<RulePlatform>) -> &'static str {
    match p {
        Some(RulePlatform::Windows) => "Some(RulePlatform::Windows)",
        None => "None",
    }
}

/// A string literal (`{:?}` of a `str` is valid Rust).
fn s(v: &Str) -> String {
    format!("Cow::Borrowed({:?})", &**v)
}

fn opt(v: &Option<Str>) -> String {
    match v {
        Some(v) => format!("Some({})", s(v)),
        None => "None".to_string(),
    }
}

fn list<T: Clone>(items: &[T], each: fn(&T) -> String) -> String {
    let items: Vec<String> = items.iter().map(each).collect();
    format!("Cow::Borrowed(&[{}])", items.join(", "))
}
